"""
最大容量：贪心算法

在给定的柱子高度数组中，找到两条柱子能盛装的最大容量。
容量由两条柱子的较小高度和它们之间的距离决定。

贪心策略：
1. 使用双指针从两端开始
2. 每次移动较短的柱子（高度较小的一端）
3. 保证不会错过可能的最大值

参数：
    ht: 各柱子的高度数组

返回：
    最大容量值
    """
def max_capacity(ht: list[int]) -> int:
    # 初始化双指针，分别指向数组两端
    i, j = 0, len(ht) - 1
    
    # 初始化最大容量为 0
    res = 0
    
    # 循环贪心选择，直至两指针相遇
    while i < j:
        # 计算当前位置的容量
        # 容量 = min(左柱高, 右柱高) × 两柱之间的距离
        cap = min(ht[i], ht[j]) * (j - i)
        
        # 更新最大容量
        res = max(res, cap)
        
        # 贪心选择：移动较短的柱子
        # 原因：移动较长的柱子只会使容量变小（距离减小，高度不会增加）
        # 而移动较短的柱子可能找到更高的柱子，增加容量
        if ht[i] < ht[j]:
            i += 1  # 左指针右移
        else:
            j -= 1  # 右指针左移
    
    return res

"""Driver Code"""
if __name__ == "__main__":
    # 测试数据：各柱子的高度
    ht = [3, 8, 5, 2, 7, 7, 3, 4]
    
    # 使用贪心算法求解最大容量
    res = max_capacity(ht)
    print(f"最大容量为 {res}")