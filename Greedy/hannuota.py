"""
汉诺塔问题 (Tower of Hanoi)

问题描述：
  给定三根柱子 A、B、C，柱子 A 上有 n 个不同大小的圆盘，大圆盘在下，小圆盘在上。
  要求在遵循以下规则的情况下，将柱子 A 上的所有圆盘移到柱子 C 上：
  - 每次只能移动一个圆盘
  - 大圆盘不能放在小圆盘上面
  - 可以借助柱子 B 作为辅助

解决思路 (分治递推)：
  设 f(i) 表示将 i 个圆盘从源柱移到目标柱的操作序列。
  递推关系：f(i) = f(i-1) + move(1) + f(i-1)
  - 第一步：借助目标柱，将前 i-1 个圆盘从源柱移到辅助柱
  - 第二步：将最大的第 i 个圆盘从源柱移到目标柱
  - 第三步：借助源柱，将 i-1 个圆盘从辅助柱移到目标柱
  
时间复杂度：O(2^n - 1)  （需要 2^n - 1 次移动）
空间复杂度：O(n)        （递归调用栈深度）
"""


def move(src: list[int], tar: list[int]) -> None:
    """
    原子操作：移动一个圆盘
    
    从源柱的顶部移除一个圆盘，放到目标柱的顶部。
    列表的末尾代表柱子的顶部。
    
    参数：
        src: 源柱（列表表示）
        tar: 目标柱（列表表示）
    """
    tar.append(src.pop())

def dfs(i: int, src: list[int], buf: list[int], tar: list[int]) -> None:
    """
    递推求解汉诺塔问题 f(i)
    
    将 i 个圆盘从源柱 src 借助 buf 移到目标柱 tar。
    
    递推过程：
    1. 基础情况 (i == 1)：直接将圆盘从源柱移到目标柱
    2. 递推情况 (i > 1)：
       - 调用 f(i-1) 将顶部 i-1 个圆盘从 src 借助 tar 移到 buf
       - 移动最大的第 i 个圆盘从 src 到 tar
       - 调用 f(i-1) 将 buf 中的 i-1 个圆盘借助 src 移到 tar
    
    参数：
        i:   需要移动的圆盘数量
        src: 源柱
        buf: 辅助柱
        tar: 目标柱
    """
    # 基础情况：只需移动一个圆盘
    if i == 1:
        move(src, tar)
        return
    
    # 递推情况 (i > 1)
    # 第一步：借助目标柱，将 i-1 个圆盘从源柱移到辅助柱
    dfs(i - 1, src, tar, buf)
    
    # 第二步：将最大圆盘（第 i 个）从源柱移到目标柱
    move(src, tar)
    
    # 第三步：借助源柱，将 i-1 个圆盘从辅助柱移到目标柱
    dfs(i - 1, buf, src, tar)

def solve_hanota(A: list[int], B: list[int], C: list[int]) -> None:
    """
    求解汉诺塔问题的公共接口
    
    将柱子 A 上的所有圆盘通过辅助柱 B 移到目标柱 C。
    
    使用分治递推思想：将 n 个圆盘的问题分解为两个 n-1 个圆盘的子问题和一个原子操作。
    
    参数：
        A: 源柱，初始包含 n 个圆盘（按大小升序排列）
        B: 辅助柱，初始为空
        C: 目标柱，初始为空
    
    时间复杂度：O(2^n - 1)
    空间复杂度：O(n)
    """
    if not A:
        return
    
    n = len(A)
    # 调用递推函数，将 n 个圆盘从 A 借助 B 移到 C
    dfs(n, A, B, C)

